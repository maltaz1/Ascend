-- ============================================================
-- Assinatura PRO pelas lojas (Google Play / App Store via RevenueCat).
--
-- 1. profiles.pro_source: de onde veio o PRO atual.
--      'cakto' → assinatura pelo site
--      'store' → assinatura pelo app (Google Play / App Store)
--      NULL    → usuário Free, ou PRO antigo/manual (tratado como site)
--    Cada webhook só desliga o PRO que ele mesmo ligou, para que o fim
--    de uma assinatura na loja não derrube quem paga pelo site e vice-versa.
-- 2. O gatilho anti-autopromoção passa a proteger também pro_source.
-- 3. revenuecat_webhook_events: registro/idempotência dos eventos.
-- ============================================================

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS pro_source text
  CHECK (pro_source IN ('cakto', 'store'));

CREATE OR REPLACE FUNCTION public.prevent_is_pro_escalation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
BEGIN
  -- Only service_role may change is_pro / pro_source (payment webhooks, admin).
  IF (NEW.is_pro IS DISTINCT FROM OLD.is_pro
      OR NEW.pro_source IS DISTINCT FROM OLD.pro_source)
     AND current_setting('role') <> 'service_role' THEN
    RAISE EXCEPTION 'is_pro can only be changed by the server (payment webhook)';
  END IF;
  RETURN NEW;
END;
$$;

create table if not exists public.revenuecat_webhook_events (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event_type text,
  app_user_id text,
  environment text,
  payload jsonb not null,
  processed_at timestamptz not null default now()
);

create index if not exists idx_revenuecat_webhook_events_processed_at
  on public.revenuecat_webhook_events (processed_at desc);

-- Sem políticas: só o service_role (webhook) lê e escreve.
ALTER TABLE public.revenuecat_webhook_events ENABLE ROW LEVEL SECURITY;
